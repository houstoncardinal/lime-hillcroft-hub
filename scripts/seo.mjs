// SEO maintenance for TIC Wireless.
//   node scripts/seo.mjs sitemap   → regenerate public/sitemap.xml from the site's pages
//   node scripts/seo.mjs indexnow  → tell Bing/IndexNow (used by ChatGPT & Copilot search) about every URL
// Run "sitemap" after adding pages; run "indexnow" after each deploy to the live domain.
import fs from "node:fs";

const SITE = (process.env.SITE_URL ?? "https://lime-hillcroft-hub.lovable.app").replace(/\/$/, "");
const today = new Date().toISOString().slice(0, 10);
const SHOP_ON = /SHOP_ENABLED = true/.test(
  fs.readFileSync("src/components/site/features.ts", "utf8"),
);
const INTL = [
  ...fs
    .readFileSync("src/components/intl/languages.ts", "utf8")
    .matchAll(/code: "([a-z]+)",\s*tag: "([^"]+)"/g),
].map((m) => ({ code: m[1], tag: m[2] }));
const intlLinks = INTL.map(
  (l) => `    <xhtml:link rel="alternate" hreflang="${l.tag}" href="${SITE}/${l.code}"/>\n`,
).join("");
const slugs = (file) =>
  [...fs.readFileSync(file, "utf8").matchAll(/slug: "([^"]+)"/g)].map((m) => m[1]);
const handles = (file) =>
  [...fs.readFileSync(file, "utf8").matchAll(/handle: "([^"]+)"/g)].map((m) => m[1]);

// [english path, spanish path, priority, changefreq, images]
const pages = [
  ["/", "/es", "1.0", "weekly", ["/og/home.jpg", "/og/store.jpg"]],
  ["/leasing", "/es/arrendamiento", "0.9", "weekly", ["/og/leasing.jpg"]],
  ...(SHOP_ON ? [["/shop", "/es/tienda", "0.9", "daily", []]] : []),
  ["/areas", "/es/zonas", "0.8", "monthly", []],
  ["/guides", "/es/guias", "0.8", "monthly", []],
  ...slugs("src/components/areas/data.ts").map((s) => [
    `/areas/${s}`,
    `/es/zonas/${s}`,
    "0.7",
    "monthly",
    [],
  ]),
  ...slugs("src/components/guides/data.ts").map((s) => [
    `/guides/${s}`,
    `/es/guias/${s}`,
    "0.7",
    "monthly",
    [],
  ]),
  // Product pages are added once Shopify is live (preview products are noindex):
  ...(process.env.INCLUDE_PRODUCTS
    ? handles("src/shop/preview-catalog.ts").map((h) => [
        `/shop/${h}`,
        `/es/tienda/${h}`,
        "0.5",
        "weekly",
        [],
      ])
    : []),
];

const url = (loc, en, es, pr, freq, imgs) => `  <url>
    <loc>${SITE}${loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${pr}</priority>
    <xhtml:link rel="alternate" hreflang="en-US" href="${SITE}${en}"/>
    <xhtml:link rel="alternate" hreflang="es-US" href="${SITE}${es}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${en}"/>
${en === "/" ? intlLinks : ""}${imgs.map((i) => `    <image:image><image:loc>${SITE}${i}</image:loc></image:image>\n`).join("")}  </url>`;

const all = pages.flatMap(([en, es, pr, freq, imgs]) => [
  [en, en, es, pr, freq, imgs],
  [es, en, es, pr, freq, imgs],
]);

if (process.argv[2] === "sitemap") {
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/seo.mjs — run "node scripts/seo.mjs sitemap" after adding pages. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${[...all, ...INTL.map((l) => [`/${l.code}`, "/", "/es", "0.6", "monthly", []])].map((p) => url(...p)).join("\n")}
</urlset>
`;
  fs.writeFileSync("public/sitemap.xml", xml);
  console.log(`sitemap.xml: ${all.length + INTL.length} URLs`);
} else if (process.argv[2] === "indexnow") {
  const keyFile = fs.readdirSync("public").find((f) => /^[0-9a-f]{32}\.txt$/.test(f));
  if (!keyFile) throw new Error("IndexNow key file missing in public/");
  const key = keyFile.replace(".txt", "");
  const res = await fetch("https://api.indexnow.org/indexnow", {
    method: "POST",
    headers: { "Content-Type": "application/json; charset=utf-8" },
    body: JSON.stringify({
      host: new URL(SITE).host,
      key,
      keyLocation: `${SITE}/${keyFile}`,
      urlList: [...all.map(([loc]) => `${SITE}${loc}`), ...INTL.map((l) => `${SITE}/${l.code}`)],
    }),
  });
  console.log(`IndexNow: ${res.status} ${res.statusText} (${all.length} URLs)`);
} else {
  console.log("Usage: node scripts/seo.mjs sitemap | indexnow");
}
